function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--source') parsed.source = argv[++i];
    else if (arg === '--ref') parsed.ref = argv[++i];
    else if (arg === '--allow-unpublished') parsed.allowUnpublished = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return parsed;
}

function git(cwd, gitArgs) {
  return execFileSync('git', gitArgs, {cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']});
}

function prepareSource({source: sourcePath, ref = 'stable', allowUnpublished}) {
  if (sourcePath) {
    const resolved = path.resolve(sourcePath);
    let origin = '';
    try {
      origin = git(resolved, ['remote', 'get-url', 'origin']).trim();
    } catch {
      // No origin: treat as unpublished.
    }
    if (!PUBLIC_REPOSITORY_PATTERN.test(origin) && !allowUnpublished) {
      throw new Error(
        `${resolved} is not a checkout of ${PUBLIC_REPOSITORY} (origin: ${origin || 'none'}). ` +
          'Its documents may not be public. Pass --allow-unpublished to import it anyway.',
      );
    }
    return resolved;
  }
  // A blobless clone keeps tags and history (for release dates) without downloading every file.
  const cache = path.join(siteRoot, '.cache', 'ograf-studio');
  if (!fs.existsSync(path.join(cache, '.git'))) {
    fs.mkdirSync(path.dirname(cache), {recursive: true});
    execFileSync('git', ['clone', '--quiet', '--filter=blob:none', PUBLIC_REPOSITORY, cache], {
      stdio: 'inherit',
    });
  } else {
    git(cache, ['fetch', '--quiet', '--tags', '--force', 'origin']);
  }
  let target = ref;
  try {
    target = git(cache, ['rev-parse', '--verify', '--quiet', `origin/${ref}`]).trim();
  } catch {
    // Not a branch: a tag or commit, checked out as given.
  }
  git(cache, ['checkout', '--quiet', '--detach', target]);
  return cache;
}

function collectDocs(root) {
  const docsDir = path.join(root, 'docs');
  const files = fs
    .readdirSync(docsDir)
    .filter((name) => name.endsWith('.md'))
    .map((name) => `docs/${name}`);
  return files
    .map((from, index) => {
      const known = KNOWN_DOCS[from];
      const stem = path.basename(from, '.md');
      return {
        from,
        slug: known?.slug ?? stem.toLowerCase().replace(/_/g, '-'),
        label: known?.label,
        position: known?.position ?? 10 + index,
      };
    })
    .sort((a, b) => a.position - b.position);
}

function collectReleases(root) {
  const releasesDir = path.join(root, 'docs', 'releases');
  if (!fs.existsSync(releasesDir)) return [];
  return fs
    .readdirSync(releasesDir)
    .filter((name) => /^\d+\.\d+(\.\d+)?(-[\w.]+)?\.md$/.test(name))
    .flatMap((name) => {
      const version = name.replace(/\.md$/, '');
      const from = `docs/releases/${name}`;
      const pointer = RELEASE_POINTER.exec(fs.readFileSync(path.join(root, from), 'utf8'));
      if (pointer) {
        releasePointers.set(from, `/releases/${pointer[1]}`);
        return [];
      }
      return [{from, version, prerelease: version.includes('-')}];
    })
    .sort((a, b) => compareVersions(b.version, a.version));
}

function compareVersions(a, b) {
  const parse = (v) => {
    const [core, pre = ''] = v.split('-');
    return {parts: core.split('.').map(Number), pre};
  };
  const pa = parse(a);
  const pb = parse(b);
  for (let i = 0; i < Math.max(pa.parts.length, pb.parts.length); i++) {
    const diff = (pa.parts[i] ?? 0) - (pb.parts[i] ?? 0);
    if (diff) return diff;
  }
  if (pa.pre === pb.pre) return 0;
  if (!pa.pre) return 1;
  if (!pb.pre) return -1;
  return pa.pre.localeCompare(pb.pre, 'en', {numeric: true});
}

function removeGeneratedFiles(dir) {
  if (!fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isFile() && fs.readFileSync(file, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(file);
    }
  }
}

function frontMatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, value]) => value !== undefined && value !== null)
    .map(([key, value]) => {
      if (Array.isArray(value)) return `${key}: [${value.join(', ')}]`;
      // An unquoted YAML timestamp reaches Docusaurus as a date, not a string.
      if (key === 'date') return `${key}: ${value}`;
      return `${key}: ${JSON.stringify(value)}`;
    });
  return `---\n${lines.join('\n')}\n---\n`;
}

function generatedComment(from) {
  return `<!-- ${GENERATED_MARKER} from ${blobBase}/${from}. Edit the source document, not this file. -->\n`;
}

/** Splits off the leading "# Title" line and returns the rest of the document. */
function splitTitle(markdown) {
  const match = /^#\s+(.+?)\s*\n/.exec(markdown.replace(/^﻿/, ''));
  if (!match) return {title: undefined, body: markdown};
  return {title: stripMarkdown(match[1]), body: markdown.slice(match.index + match[0].length)};
}

function stripMarkdown(text) {
  return text
    .replace(/<[^>]+>/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[*_`]/g, '')
    .trim();
}

function firstParagraph(body) {
  for (const block of body.split(/\n\s*\n/)) {
    const text = block.trim();
    if (text && !/^([#>|`<-]|\d+\.|\*\s)/.test(text)) return stripMarkdown(text.replace(/\n/g, ' '));
  }
  return undefined;
}

/** Rewrites one relative link from a repository document to its place on the site. */
function rewriteTarget(target, fromFile) {
  // A full GitHub link to a document the site also has goes to the site's copy, like a relative link.
  const onGitHub = /^https:\/\/github\.com\/zerodensity\/ograf-studio\/blob\/[^/]+\/([^#?]+)(?:#(.*))?$/i.exec(target);
  if (onGitHub) {
    const [, repoPath, hash] = onGitHub;
    if (repoPath === USER_GUIDE && hash) return userGuideLink(hash);
    if (routes.has(repoPath) && repoPath !== 'README.md') return `${routes.get(repoPath)}${hash ? `#${hash}` : ''}`;
    return target;
  }
  // A leading slash is already a place on the site: the guide's own links arrive here as routes.
  if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return target;
  const [rawPath, hash = ''] = target.split('#');
  const anchor = hash ? `#${hash}` : '';
  if (!rawPath) return target;
  const repoPath = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), rawPath));
  if (repoPath === USER_GUIDE && hash) return userGuideLink(hash);
  if (routes.has(repoPath)) return `${routes.get(repoPath)}${anchor}`;
  const absolute = path.join(source, repoPath);
  if (IMAGE_EXTENSIONS.has(path.posix.extname(repoPath).toLowerCase()) && fs.existsSync(absolute)) {
    const destination = path.join(siteRoot, 'static', 'img', 'repo', repoPath);
    fs.mkdirSync(path.dirname(destination), {recursive: true});
    fs.copyFileSync(absolute, destination);
    return `/img/repo/${repoPath}`;
  }
  const isDirectory = fs.existsSync(absolute) && fs.statSync(absolute).isDirectory();
  return `${isDirectory ? treeBase : blobBase}/${repoPath}${anchor}`;
}

function rewriteLinks(markdown, fromFile) {
  // Leave fenced code untouched.
  return markdown
    .split(/(^```[\s\S]*?^```)/m)
    .map((part, index) => {
      if (index % 2 === 1) return part;
      return part
        .replace(/(\]\()([^)\s]+)((?:\s+"[^"]*")?\))/g, (_, open, target, close) => {
          return `${open}${rewriteTarget(target, fromFile)}${close}`;
        })
        .replace(/\b(src|href|srcset)="([^"]+)"/g, (_, attribute, target) => {
          return `${attribute}="${rewriteTarget(target, fromFile)}"`;
        });
    })
    .join('');
}

/** Applies SITE_WORDING outside fenced code, and names anything it couldn't reword. */
function siteWording(markdown, fromFile) {
  const reworded = markdown
    .split(/(^```[\s\S]*?^```)/m)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : SITE_WORDING.reduce((text, [pattern, wording]) => text.replace(pattern, wording), part),
    )
    .join('');
  const left = reworded.replace(/^```[\s\S]*?^```/gm, '').match(/.*\bHTML ?5?\b.*/g) ?? [];
  for (const line of left) console.warn(`${fromFile} still says HTML: ${line.trim()}`);
  return reworded;
}

function writeDoc(doc) {
  const raw = siteWording(fs.readFileSync(path.join(source, doc.from), 'utf8'), doc.from);
  const {title, body} = splitTitle(raw);
  // The repository's "[Back to overview](../README.md) · …" line duplicates the site navigation.
  const content = body.replace(/^\s*\[Back to overview\][^\n]*\n/, '');
  const output =
    frontMatter({
      title: title ?? doc.label ?? doc.slug,
      sidebar_label: doc.label,
      sidebar_position: doc.position,
      description: firstParagraph(content),
      custom_edit_url: `${PUBLIC_REPOSITORY}/blob/${args.allowUnpublished ? 'stable' : ref}/${doc.from}`,
    }) +
    '\n' +
    generatedComment(doc.from) +
    '\n' +
    rewriteLinks(content.trimStart(), doc.from) +
    (doc.slug === 'third-party' ? SITE_CREDITS : '');
  fs.writeFileSync(path.join(siteRoot, 'docs', `${doc.slug}.md`), output);
}

/** The same anchors Docusaurus gives a heading. */
function headingAnchor(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

/** Cuts USER_GUIDE.md into named chunks. A heading stays out of the chunk's body. */
function chunksOf(markdown) {
  const chunks = [{name: '', lines: []}];
  const unused = new Set(CUTS);
  let inFence = false;
  for (const line of markdown.split('\n')) {
    if (/^```/.test(line)) inFence = !inFence;
    const heading = inFence ? null : /^#{2,4}\s+(.+?)\s*$/.exec(line);
    const cut = inFence ? undefined : CUTS.find(({at}) => line.startsWith(at));
    if (heading) {
      const name = stripMarkdown(heading[1]);
      chunks.push({name, heading: name, lines: []});
    } else if (cut) {
      unused.delete(cut);
      chunks.push({name: cut.name, lines: [cut.strip ? line.slice(cut.at.length) : line]});
    } else if (!/^<a id="[^"]+"><\/a>\s*$/.test(line)) {
      chunks.at(-1).lines.push(line);
    }
  }
  for (const {at} of unused) console.warn(`User guide: cut not found: ${at}`);
  return chunks
    .map(({lines, ...chunk}) => ({...chunk, body: lines.join('\n').trim()}))
    .filter((chunk) => chunk.heading || chunk.body);
}

/** Maps the source's chunks onto pages, and every source anchor onto its new page. */
function prepareUserGuide() {
  const raw = siteWording(fs.readFileSync(path.join(source, USER_GUIDE), 'utf8'), USER_GUIDE);
  const {body} = splitTitle(raw.replace(/\r\n/g, '\n'));
  let text = body.replace(/^\s*\[Back to overview\][^\n]*\n/, '');
  for (const [from, to] of REWORDS) {
    const found = from instanceof RegExp ? from.test(text) : text.includes(from);
    if (!found) console.warn(`User guide: rewording not found: ${String(from).slice(0, 60)}`);
    text = text.replace(from, to);
  }
  const chunks = new Map();
  for (const chunk of chunksOf(text)) {
    if (chunks.has(chunk.name)) throw new Error(`User guide: two chunks named "${chunk.name}"`);
    chunks.set(chunk.name, chunk);
  }
  const groups = GROUPS.map((group) => ({...group, pages: group.pages.map((page) => ({...page}))}));
  const taken = new Set();
  for (const group of groups) {
    for (const page of group.pages) {
      page.route = `${USER_GUIDE_ROUTE}/${group.dir}/${page.slug}`;
      page.parts = page.chunks.flatMap((name) => {
        if (!chunks.has(name)) {
          console.warn(`User guide: ${page.slug} lists a missing chunk: ${name}`);
          return [];
        }
        if (taken.has(name)) throw new Error(`User guide: "${name}" is on two pages`);
        taken.add(name);
        return [chunks.get(name)];
      });
    }
  }
  const unlisted = [...chunks.values()].filter((chunk) => !taken.has(chunk.name));
  if (unlisted.length) {
    for (const {name} of unlisted) console.warn(`User guide: no page lists "${name}"`);
    groups.push({
      dir: 'other',
      label: 'Other topics',
      description: 'Topics not sorted into a section yet.',
      pages: [
        {
          slug: 'other-topics',
          title: 'Other topics',
          route: `${USER_GUIDE_ROUTE}/other/other-topics`,
          parts: [{name: '', body: 'Topics not sorted into a section yet.'}, ...unlisted],
        },
      ],
    });
  }
  const anchors = new Map();
  for (const group of groups) {
    for (const page of group.pages) {
      page.parts.forEach((part, index) => {
        if (!part.heading) return;
        const here = index === 0 ? '' : `#${headingAnchor(TITLES[part.name] ?? part.name)}`;
        anchors.set(headingAnchor(part.heading), `${page.route}${here}`);
      });
    }
  }
  for (const [alias, name] of Object.entries(ANCHOR_ALIASES)) {
    anchors.set(alias, anchors.get(headingAnchor(name)));
  }
  return {groups, anchors};
}

function userGuideLink(anchor) {
  const link = userGuide.anchors.get(anchor);
  if (!link) console.warn(`User guide: no page for #${anchor}`);
  return link ?? USER_GUIDE_ROUTE;
}

/** The first sentence, short enough for the cards on a section's page and for search results. */
function shortDescription(body) {
  const paragraph = firstParagraph(body);
  if (!paragraph) return undefined;
  const sentence = /^.*?[.!?](?=\s|$)/.exec(paragraph)?.[0] ?? paragraph;
  return sentence.length > 180 ? `${sentence.slice(0, 177).trimEnd()}…` : sentence;
}

function writeUserGuide(doc) {
  const root = path.join(siteRoot, 'docs', 'user-guide');
  const editUrl = `${PUBLIC_REPOSITORY}/blob/${args.allowUnpublished ? 'stable' : ref}/${USER_GUIDE}`;
  userGuide.groups.forEach((group, groupIndex) => {
    const dir = path.join(root, group.dir);
    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(
      path.join(dir, '_category_.json'),
      `${JSON.stringify(
        {
          label: group.label,
          position: groupIndex + 1,
          link: {
            type: 'generated-index',
            title: group.label,
            description: group.description,
            slug: `/user-guide/${group.dir}`,
          },
        },
        null,
        2,
      )}\n`,
    );
    group.pages.forEach((page, pageIndex) => {
      const body = page.parts
        .map((part, index) =>
          index === 0 ? part.body : `## ${TITLES[part.name] ?? part.name}\n\n${part.body}`,
        )
        .join('\n\n')
        .replace(/\]\(#([^)\s]+)\)/g, (_, anchor) => `](${userGuideLink(anchor)})`);
      const output =
        frontMatter({
          title: page.title,
          sidebar_label: page.label,
          sidebar_position: pageIndex + 1,
          description: shortDescription(page.parts[0]?.body ?? ''),
          custom_edit_url: editUrl,
        }) +
        '\n' +
        generatedComment(USER_GUIDE) +
        '\n' +
        rewriteLinks(body, USER_GUIDE) +
        '\n';
      fs.writeFileSync(path.join(dir, `${page.slug}.md`), output);
    });
  });
  fs.writeFileSync(
    path.join(root, '_category_.json'),
    `${JSON.stringify({label: doc.label, position: doc.position, collapsed: false}, null, 2)}\n`,
  );
  const contents = userGuide.groups
    .map(
      (group) =>
        `## ${group.label}\n\n${group.description}\n\n` +
        group.pages.map((page) => `- [${page.title}](${page.route})`).join('\n'),
    )
    .join('\n\n');
  fs.writeFileSync(
    path.join(root, 'index.md'),
    frontMatter({
      title: 'User guide',
      sidebar_label: doc.label,
      description: 'How to use every feature of OGraf Studio, sorted by what you are trying to do.',
      custom_edit_url: editUrl,
    }) +
      '\n' +
      generatedComment(USER_GUIDE) +
      '\n' +
      'How to use every feature of OGraf Studio, sorted by what you are trying to do. New to Studio? ' +
      'Start with the [how-to guides](/guides).\n\n' +
      contents +
      '\n',
  );
}

function releaseDate(releaseBody, version) {
  const stated = /^Released:\s*(\d{4}-\d{2}-\d{2})\s*$/m.exec(releaseBody);
  if (stated) return stated[1];
  for (const tag of [`v${version}`, version]) {
    try {
      return git(source, ['log', '-1', '--format=%as', tag]).trim();
    } catch {
      // Tag not present; fall through.
    }
  }
  return git(source, ['log', '-1', '--format=%as', '--', `docs/releases/${version}.md`]).trim();
}

/** Puts the truncate marker after enough opening blocks for a useful excerpt, never after a heading. */
function withTruncate(body) {
  const blocks = body.trim().split(/\n\s*\n/);
  let cut = 0;
  let length = 0;
  while (cut < blocks.length && (length < 120 || /^#{2,}\s/.test(blocks[cut - 1]))) {
    length += stripMarkdown(blocks[cut]).length;
    cut++;
  }
  return `${blocks.slice(0, cut).join('\n\n')}\n\n<!-- truncate -->\n\n${blocks.slice(cut).join('\n\n')}\n`;
}

function readRelease(release) {
  return splitTitle(siteWording(fs.readFileSync(path.join(source, release.from), 'utf8'), release.from));
}

function writeRelease(release) {
  const {title, body} = readRelease(release);
  const content = body.replace(/^\s*Released:\s*\d{4}-\d{2}-\d{2}\s*\n/m, '').trimStart();
  const output =
    frontMatter({
      title: title ?? `OGraf Studio ${release.version}`,
      slug: `/${release.version}`,
      date: release.date,
      description: firstParagraph(content) ?? `Release notes for OGraf Studio ${release.version}.`,
      authors: ['ograf-studio'],
      tags: [release.prerelease ? 'release-candidate' : 'release'],
    }) +
    '\n' +
    generatedComment(release.from) +
    '\n' +
    rewriteLinks(withTruncate(content), release.from);
  fs.writeFileSync(path.join(siteRoot, 'releases', `${release.day}-${release.version}.md`), output);
}
