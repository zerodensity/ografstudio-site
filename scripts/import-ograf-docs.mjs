#!/usr/bin/env node
// Imports OGraf Studio's documentation and release notes into this site.
//
//   npm run import:docs                       # public zerodensity/ograf-studio, branch "stable"
//   npm run import:docs -- --ref dev          # another branch, tag or commit of the public repo
//   npm run import:docs -- --source ../ograf-studio
//
// The site is public, so a --source checkout must have the public repository as its origin.
// Pass --allow-unpublished only when everything in that checkout may be published:
//
//   npm run import:docs -- --source ../ograf-studio-dev --ref dev --allow-unpublished
//
// Such an import links to the public "stable" branch, because the private commit doesn't exist in
// the public repository.
//
// Generated files carry GENERATED_MARKER and are replaced on every run. Hand-written pages in
// docs/ and releases/ are left alone.

